export function fileIconFor(type) {
  const t = (type || "").toUpperCase();
  if (t.includes("PDF")) return FILE_ICONS.PDF;
  if (t.includes("DOC")) return FILE_ICONS.DOCX;
  if (t.includes("PNG") || t.includes("JPG") || t.includes("JPEG") || t.includes("IMAGE")) return FILE_ICONS.IMAGE;
  return FILE_ICONS.default;
}

